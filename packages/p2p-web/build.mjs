// Bundles the browser node (src/p2p/web/worker.ts) with esbuild into public/p2p-worker.js.
//   node packages/p2p-web/build.mjs [--out file] [--no-minify] [--meta]
// Root script: `npm run build:p2p-worker`. Run it before `expo export -p web`.
//
// One copy of every shared module (the dht-relay fork resolves its own from the gateway's node_modules for
// its tests): b4a, sodium, hyperdht, protomux, ... are pinned to the app's copies.
import { build } from 'esbuild'
import { createRequire } from 'node:module'
import path from 'node:path'
import fs from 'node:fs'
import zlib from 'node:zlib'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.join(here, '..', '..')
const web = path.join(repo, 'src', 'p2p', 'web')
const shims = path.join(web, 'shims')
const requireHere = createRequire(path.join(here, 'package.json'))
const requireRoot = createRequire(path.join(repo, 'package.json'))
const dir = (req, name) => path.dirname(req.resolve(name + '/package.json'))
const rootDir = (name) => {
  try {
    return dir(requireRoot, name)
  } catch {
    // packages without "./package.json" in their exports
    let p = path.dirname(requireRoot.resolve(name))
    while (!fs.existsSync(path.join(p, 'package.json'))) p = path.dirname(p)
    return p
  }
}

// bip39-mnemonic requires './wordlist' (12 languages + lookup table, ~1 MB): English only.
const bip39Dir = rootDir('bip39-mnemonic')
const bip39English = {
  name: 'bip39-english',
  setup(b) {
    b.onResolve({ filter: /^\.\/wordlist$/ }, (args) => (args.importer.includes('bip39-mnemonic') ? { path: path.join(shims, 'bip39-wordlist.js') } : undefined))
  }
}

const SHARED = ['nanoassert', '@hyperswarm/secret-stream', 'compact-encoding', 'compact-encoding-net', 'hyperdht', 'noise-curve-ed', 'noise-handshake', 'protomux', 'safety-catch', 'sodium-universal', 'streamx', 'timeout-refresh', 'hypercore-crypto']

export async function bundle({ outfile = path.join(repo, 'public', 'p2p-worker.js'), minify = true, meta = false } = {}) {
  fs.mkdirSync(path.dirname(outfile), { recursive: true })
  const alias = {
    'rocksdb-idb': path.join(repo, 'packages', 'rocksdb-idb'),
    'rocksdb-native': path.join(repo, 'packages', 'rocksdb-idb'),
    '@huwa/dht-relay': path.join(repo, 'services', 'huwa-gateway', 'dht-relay'),
    // b4a in its Node flavour over the Buffer polyfill installed by shims/globals.js
    b4a: path.join(rootDir('b4a'), 'index.js'),
    buffer: dir(requireHere, 'buffer'),
    events: dir(requireHere, 'events'),
    'sodium-javascript': dir(requireHere, 'sodium-javascript'),
    'blake2b-wasm': dir(requireHere, 'blake2b-wasm'),
    'sodium-native': path.join(shims, 'sodium.js'),
    fs: path.join(shims, 'fs.js'),
    'fs/promises': path.join(shims, 'fs.js'),
    path: path.join(shims, 'path.js'),
    os: path.join(shims, 'os.js'),
    'device-file': path.join(shims, 'device-file.js'),
    'bip39-english-wordlist': path.join(bip39Dir, 'wordlist', 'english.json')
  }
  for (const name of SHARED) alias[name] = rootDir(name)
  const result = await build({
    entryPoints: [path.join(web, 'worker.ts')],
    bundle: true,
    outfile,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify,
    metafile: true,
    sourcemap: false,
    logLevel: 'warning',
    legalComments: 'eof',
    banner: { js: '/* Huwa browser node (src/p2p/web/worker.ts) — generated by packages/p2p-web/build.mjs */' },
    plugins: [bip39English],
    inject: [path.join(shims, 'globals.js')],
    define: { 'process.env.NODE_DEBUG': 'undefined', 'process.env.RELAY_DEBUG': 'undefined' },
    // "browser" fields first (hyperdht -> its stub).
    mainFields: ['browser', 'module', 'main'],
    conditions: ['browser'],
    nodePaths: [path.join(here, 'node_modules'), path.join(repo, 'node_modules')],
    alias
  })
  if (meta) fs.writeFileSync(outfile.replace(/\.js$/, '.meta.json'), JSON.stringify(result.metafile))
  const buf = fs.readFileSync(outfile)
  const sizes = { bytes: buf.byteLength, gzip: zlib.gzipSync(buf, { level: 9 }).byteLength, brotli: zlib.brotliCompressSync(buf).byteLength }
  const byPkg = new Map()
  const rel = path.relative(process.cwd(), outfile)
  for (const [file, info] of Object.entries(result.metafile.outputs[rel]?.inputs || {})) {
    const m = /node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(file)
    const k = m ? m[1] : file.includes('src/p2p') ? 'src/p2p (Huwa)' : file.includes('packages/') ? file.split('/').slice(0, 2).join('/') : 'other'
    byPkg.set(k, (byPkg.get(k) || 0) + info.bytesInOutput)
  }
  sizes.top = [...byPkg.entries()].sort((a, b) => b[1] - a[1]).slice(0, 12).map(([k, v]) => [k, Math.round(v / 1024) + ' KiB'])
  return { outfile, sizes, inputs: Object.keys(result.metafile.inputs) }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--out')
  const { outfile, sizes } = await bundle({
    outfile: i === -1 ? undefined : path.resolve(process.argv[i + 1]),
    minify: !process.argv.includes('--no-minify'),
    meta: process.argv.includes('--meta')
  })
  console.log(path.relative(process.cwd(), outfile), JSON.stringify(sizes))
}
