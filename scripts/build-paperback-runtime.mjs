// Bundles the Paperback extension sandbox (src/manga-ext/runtime/entry.ts + cheerio) into a
// browser IIFE and writes it as a string module the app injects into its hidden WebView.
// Runs on postinstall; output is git-ignored like the Bare worklet bundle.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);

export async function bundleRuntime() {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('src/manga-ext/runtime/entry.ts', root))],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    // WKWebView on iOS 15.1+ (Expo 57 minimum).
    target: 'safari15',
    minify: true,
    legalComments: 'none',
    write: false,
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = await bundleRuntime();
  const out = fileURLToPath(new URL('src/manga-ext/runtime/runtime.bundle.js', root));
  writeFileSync(out, `// Generated by scripts/build-paperback-runtime.mjs, do not edit.\nmodule.exports = ${JSON.stringify(code)};\n`);
  console.log(`paperback runtime: ${(code.length / 1024).toFixed(0)} KB -> ${out}`);
}
